"""
V2_PLAN.md WP5, item 1-2: the main offline evaluation over 10 seeds
(data seed = split seed = model seed), with run-level bootstrap CIs.

DEVELOPMENT MODE (default): train and validation only. Each seed's model
is trained on its train split and its thresholds are tuned on its val
split, and the metrics are computed on that same val split. Threshold-
dependent metrics (F1, step recall, runs caught, benign false alarm) are
therefore optimistic in development mode; AUPRC is threshold-free. Test,
held-out types and variant B are generated by the generator (one random
stream) but discarded unread. --confirmatory scores them and is refused
until experiments/v2/PREREGISTRATION_HASHES.md records the current hash
of PREREGISTRATION_v2.md.

Seed 42 is the frozen reference. Without touching test data it is checked
by: the retrained seed-42 model reproduces models/thresholds.json exactly
and the frozen model's validation scores (max abs difference reported).

CIs: 95% percentile bootstrap, resampling runs (not rows) within each
seed and averaging over seeds. Per-attack-type run catch: pooled counts
over seeds with a Wilson CI.

    python experiments/v2/multiseed_eval.py            # development
"""
import argparse
import json
import os
import pickle
import sys
import time

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, HERE)
sys.path.insert(0, ROOT)

from sklearn.metrics import average_precision_score, f1_score  # noqa: E402

from data.generate_trajectories import generate_dataset  # noqa: E402
from governance.features import FEATURE_SETS  # noqa: E402
from models.train_models import (  # noqa: E402
    FINAL_FEATURE_SET, GROUP_COL, LABEL_COL, split_by_trajectory, train_model, tune_thresholds,
)
from precedence_ablation import OUT_DIR, prereg_frozen  # noqa: E402

SEEDS = [42, 1, 2, 3, 4, 5, 6, 7, 8, 9]
BOOT = 1000
FEATURES = FEATURE_SETS[FINAL_FEATURE_SET]


def wilson(k, n, z=1.96):
    if n == 0:
        return [None, None]
    p = k / n
    d = 1 + z * z / n
    c = (p + z * z / (2 * n)) / d
    h = z * np.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / d
    return [float(max(0, c - h)), float(min(1, c + h))]


def run_index(df):
    """Row positions grouped by run, for run-level resampling."""
    groups = {}
    for pos, rid in enumerate(df[GROUP_COL].to_numpy()):
        groups.setdefault(rid, []).append(pos)
    return [np.array(v) for v in groups.values()]


def metrics(y, prob, attack, t2, rows=None):
    if rows is not None:
        y, prob, attack = y[rows], prob[rows], attack[rows]
    stopped = prob >= t2
    unsafe = y == 1
    out = {"f1": f1_score(y, stopped, zero_division=0),
           "auprc": average_precision_score(y, prob) if unsafe.any() and (~unsafe).any() else np.nan,
           "step_recall": stopped[unsafe].mean() if unsafe.any() else np.nan}
    return out


def run_level(df, prob, t2, rows_by_run):
    stopped = prob >= t2
    y = df[LABEL_COL].to_numpy()
    types = df["attack_type"].to_numpy()
    caught, benign_alarm = [], []
    for rows in rows_by_run:
        if types[rows[0]] == "benign":
            benign_alarm.append(stopped[rows].any())
        else:
            unsafe_rows = rows[y[rows] == 1]
            if len(unsafe_rows):
                caught.append(stopped[unsafe_rows].any())
    return np.array(caught), np.array(benign_alarm)


def evaluate(df, prob, t2, rng):
    y = df[LABEL_COL].to_numpy()
    attack = (df["attack_type"] != "benign").to_numpy()
    runs = run_index(df)
    point = metrics(y, prob, attack, t2)
    caught, alarm = run_level(df, prob, t2, runs)
    point["runs_caught"] = caught.mean()
    point["benign_run_false_alarm"] = alarm.mean()
    # run-level bootstrap replicates for this seed
    reps = []
    for _ in range(BOOT):
        pick = rng.integers(0, len(runs), len(runs))
        sample = [runs[i] for i in pick]
        rows = np.concatenate(sample)
        m = metrics(y, prob, attack, t2, rows)
        c, a = run_level(df.iloc[rows].reset_index(drop=True), prob[rows], t2,
                         _reindex(sample))
        m["runs_caught"] = c.mean() if len(c) else np.nan
        m["benign_run_false_alarm"] = a.mean() if len(a) else np.nan
        reps.append(m)
    per_type = {}
    types = df["attack_type"].to_numpy()
    stopped = prob >= t2
    for rows in runs:
        t = types[rows[0]]
        if t == "benign":
            continue
        unsafe_rows = rows[y[rows] == 1]
        if len(unsafe_rows):
            k, n = per_type.get(t, (0, 0))
            per_type[t] = (k + int(stopped[unsafe_rows].any()), n + 1)
    return point, reps, per_type


def _reindex(sample):
    out, start = [], 0
    for rows in sample:
        out.append(np.arange(start, start + len(rows)))
        start += len(rows)
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--confirmatory", action="store_true")
    args = ap.parse_args()
    if args.confirmatory:
        sys.exit("Refused: confirmatory sets are not implemented here until the pre-registration "
                 "is frozen" if not prereg_frozen() else
                 "Confirmatory scoring is deliberately not implemented in this development script.")
    rng = np.random.default_rng(0)
    with open(os.path.join(ROOT, "models", "thresholds.json"), encoding="utf-8") as f:
        frozen_thresholds = json.load(f)
    with open(os.path.join(ROOT, "models", "trajectory_level_model.pkl"), "rb") as f:
        frozen_model = pickle.load(f)

    report = {"mode": "development", "set": "val", "seeds": SEEDS, "bootstrap": BOOT,
              "feature_set": FINAL_FEATURE_SET, "per_seed": {}, "per_attack_type": {}}
    all_reps, pooled_types = [], {}
    for seed in SEEDS:
        t0 = time.time()
        data = generate_dataset(seed=seed, write_csv=False)
        train, val, _test_unread = split_by_trajectory(data["main"], seed=seed)
        del data   # held-out sets discarded unread
        model = train_model(train, FEATURES, seed=seed)
        prob = model.predict_proba(val[FEATURES])[:, 1]
        thresholds = tune_thresholds(val[LABEL_COL], prob)
        point, reps, per_type = evaluate(val.reset_index(drop=True), prob,
                                         thresholds["restricted_max"], rng)
        entry = {"thresholds": thresholds, **{k: float(v) for k, v in point.items()},
                 "val_runs": int(val[GROUP_COL].nunique()), "seconds": round(time.time() - t0, 1)}
        if seed == 42:
            frozen_prob = frozen_model.predict_proba(val[FEATURES])[:, 1]
            entry["reproduces_frozen_thresholds"] = thresholds == frozen_thresholds
            entry["max_abs_diff_vs_frozen_val_scores"] = float(np.max(np.abs(frozen_prob - prob)))
        report["per_seed"][str(seed)] = entry
        all_reps.append(reps)
        for t, (k, n) in per_type.items():
            pk, pn = pooled_types.get(t, (0, 0))
            pooled_types[t] = (pk + k, pn + n)
        print(f"seed {seed}: {json.dumps({k: round(v, 4) if isinstance(v, float) else v for k, v in entry.items()})}",
              flush=True)

    keys = ["f1", "auprc", "step_recall", "runs_caught", "benign_run_false_alarm"]
    summary = {}
    for k in keys:
        means = np.array([np.nanmean([all_reps[s][b][k] for s in range(len(SEEDS))])
                          for b in range(BOOT)])
        point = float(np.mean([report["per_seed"][str(s)][k] for s in SEEDS]))
        lo, hi = np.nanpercentile(means, [2.5, 97.5])
        summary[k] = {"mean_over_seeds": point, "ci95": [float(lo), float(hi)],
                      "seed_min": float(min(report["per_seed"][str(s)][k] for s in SEEDS)),
                      "seed_max": float(max(report["per_seed"][str(s)][k] for s in SEEDS))}
    report["summary"] = summary
    report["per_attack_type"] = {t: {"runs_caught": k, "runs": n, "rate": k / n, "wilson95": wilson(k, n)}
                                 for t, (k, n) in sorted(pooled_types.items())}

    os.makedirs(OUT_DIR, exist_ok=True)
    stem = os.path.join(OUT_DIR, "multiseed_dev")
    with open(stem + ".json", "w", encoding="utf-8") as f:
        json.dump(report, f, indent=2)
    s42 = report["per_seed"]["42"]
    lines = ["# Multi-seed offline evaluation (DEVELOPMENT, validation split only)", "",
             f"Seeds {SEEDS} (data = split = model seed). Thresholds tuned on each seed's val split and "
             "metrics computed on the same split, so threshold-dependent metrics are optimistic; AUPRC is "
             "threshold-free. No test, held-out-type or variant-B data was scored.", "",
             f"Seed-42 reference check: thresholds reproduce `models/thresholds.json`: "
             f"**{s42['reproduces_frozen_thresholds']}**; max |frozen − retrained| val score: "
             f"{s42['max_abs_diff_vs_frozen_val_scores']:.2e}.", "",
             f"| Metric | Mean over seeds | 95% CI (run bootstrap, {BOOT}×) | Seed min–max |", "|---|---|---|---|"]
    for k in keys:
        x = summary[k]
        lines.append(f"| {k} | {x['mean_over_seeds']:.3f} | [{x['ci95'][0]:.3f}, {x['ci95'][1]:.3f}] | "
                     f"{x['seed_min']:.3f}–{x['seed_max']:.3f} |")
    lines += ["", "## Run-level catch per attack type (val, pooled over seeds; Wilson 95%)", "",
              "| Attack type | Runs caught / runs | Rate | Wilson 95% |", "|---|---|---|---|"]
    for t, x in report["per_attack_type"].items():
        lines.append(f"| {t} | {x['runs_caught']}/{x['runs']} | {x['rate']:.3f} | "
                     f"[{x['wilson95'][0]:.3f}, {x['wilson95'][1]:.3f}] |")
    lines += ["", "Held-out attack types (including `path_cross_agent_leak`) do not appear in train/val; "
              "whether 6/107 is typical needs the confirmatory held-out sets after freezing."]
    with open(stem + ".md", "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote", stem + ".json and .md")


if __name__ == "__main__":
    main()
