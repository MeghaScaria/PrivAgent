# ------------------------------------------------------------------------------------------ inline
UNICODE = {
    "–": "--", "—": "---", "→": r"$\rightarrow$", "−": "$-$", "±": r"$\pm$", "×": r"$\times$",
    "≤": r"$\le$", "≥": r"$\ge$", "≈": r"$\approx$", "²": r"\textsuperscript{2}", "·": r"$\cdot$",
    "§": r"\S{}", "‘": "`", "’": "'", "“": "``", "”": "''",
}
ESC = {"\\": r"\textbackslash{}", "&": r"\&", "%": r"\%", "$": r"\$", "#": r"\#", "_": r"\_",
       "{": r"\{", "}": r"\}", "~": r"\textasciitilde{}", "^": r"\textasciicircum{}"}


def escape(text):
    return "".join(ESC.get(c, c) for c in text)


class Inline:
    """Converts one Markdown span to LaTeX, protecting comments, code, math, citations and URLs."""

    def __init__(self, table_refs=True):
        self.table_refs = table_refs

    def __call__(self, text):
        store = []

        def keep(s):
            store.append(s)
            return f"\x00{len(store) - 1}\x00"

        def comment(m):
            body = " ".join(m.group(1).split())
            return keep(f"%{(' ' + body) if body else ''}\n")

        text = re.sub(r"\s*<!--(.*?)-->\s*", lambda m: " " + comment(m), text, flags=re.S)

        def code(m):
            c = m.group(1)
            if any(ch in c for ch in "%#{}\\^~"):
                return keep(r"\texttt{" + escape(c) + "}")
            return keep(r"\code{" + c + "}")

        text = re.sub(r"`([^`]+)`", code, text)
        text = re.sub(r"\$\$(.+?)\$\$", lambda m: keep(r"\[" + m.group(1) + r"\]"), text)
        text = re.sub(r"\$([^$]+)\$", lambda m: keep("$" + m.group(1) + "$"), text)
        text = text.replace(r"\|", keep(r"$\mid$"))

        def cites(m):
            keys = re.findall(r"\[@([a-z_]+)\]", m.group(0))
            return keep(r"\cite{" + ",".join(keys) + "}")

        text = re.sub(r"\[@[a-z_]+\](?:,\s*\[@[a-z_]+\])*", cites, text)
        text = re.sub(r"\[([^\]]+)\]\((https?://[^)\s]+)\)",
                      lambda m: m.group(1) + " (" + keep(r"\url{" + m.group(2) + "}") + ")", text)
        text = re.sub(r"https?://[^\s)|>*]+[^\s)|>*.,;]", lambda m: keep(r"\url{" + m.group(0) + "}"), text)

        text = escape(text)
        for k, v in UNICODE.items():
            text = text.replace(k, v)
        text = re.sub(r'"([^"]+)"', r"``\1''", text)
        text = re.sub(r"\*\*(.+?)\*\*", r"\\textbf{\1}", text)
        text = re.sub(r"(?<![\w*])\*(?!\s)(.+?)(?<!\s)\*(?![\w*])", r"\\emph{\1}", text)
        if self.table_refs:
            text = re.sub(r"\bTABLE ([IVX]+)\b", r"Table~\1", text)
        while "\x00" in text:
            text = re.sub(r"\x00(\d+)\x00", lambda m: store[int(m.group(1))], text)
        # merge runs of adjacent ledger comments into one line: "% P1\n % S2\n" -> "% P1; S2\n"
        prev = None
        while prev != text:
            prev = text
            text = re.sub(r"%( [^\n]*)?\n[ \t]*%( [^\n]*)?\n", lambda m: "%" + "; ".join(
                x for x in ((m.group(1) or "").strip(), (m.group(2) or "").strip()) if x).join([" ", "\n"]),
                text)
        return text.rstrip(" ")


# ------------------------------------------------------------------------------------------ blocks
def blocks(md):
    """Splits Markdown into blocks: ('h', level, text), ('comment', text), ('table', rows), ('fig', alt,
    path, trailing), ('ul'|'ol', items), ('quote', text), ('display', text), ('p', text)."""
    lines = md.split("\n")
    out, i = [], 0
    while i < len(lines):
        ln = lines[i]
        s = ln.strip()
        if not s:
            i += 1
            continue
        if s.startswith("<!--"):
            buf = [ln]
            while "-->" not in buf[-1] and i + 1 < len(lines):
                i += 1
                buf.append(lines[i])
            i += 1
            whole = "\n".join(buf).strip()
            rest = whole[whole.index("-->") + 3:].strip()
            out.append(("comment", whole[4:whole.index("-->")].strip()))
            if rest:
                out.append(("p", rest))
            continue
        m = re.match(r"^(#{1,6})\s+(.*)$", s)
        if m:
            out.append(("h", len(m.group(1)), m.group(2).strip()))
            i += 1
            continue
        if s.startswith("|"):
            rows = []
            while i < len(lines) and lines[i].strip().startswith("|"):
                rows.append(lines[i].strip())
                i += 1
            out.append(("table", rows))
            continue
        m = re.match(r"^!\[(.*?)\]\((.*?)\)(.*)$", s)
        if m:
            out.append(("fig", m.group(1), m.group(2), m.group(3).strip()))
            i += 1
            continue
        if s.startswith("$$"):
            buf = [s]
            while not (len(buf[-1]) > 2 and buf[-1].endswith("$$")) and i + 1 < len(lines):
                i += 1
                buf.append(lines[i].strip())
            i += 1
            out.append(("display", " ".join(buf)[2:-2].strip()))
            continue
        if re.match(r"^(-|\*)\s+", s) or re.match(r"^\d+\.\s+", s):
            kind = "ol" if re.match(r"^\d+\.\s+", s) else "ul"
            items = []
            while i < len(lines) and lines[i].strip():
                t = lines[i].strip()
                mm = re.match(r"^(?:-|\*|\d+\.)\s+(.*)$", t)
                if mm and (lines[i][:1] not in " \t"):
                    items.append(mm.group(1))
                else:
                    items[-1] += " " + t
                i += 1
            out.append((kind, items))
            continue
        if s.startswith(">"):
            buf = []
            while i < len(lines) and lines[i].strip().startswith(">"):
                buf.append(lines[i].strip()[1:].strip())
                i += 1
            out.append(("quote", " ".join(buf)))
            continue
        buf = []
        while i < len(lines) and lines[i].strip() and not re.match(r"^(#|\||!\[|<!--|>|\$\$)", lines[i].strip()) \
                and not re.match(r"^(-|\*)\s+|^\d+\.\s+", lines[i].strip()):
            buf.append(lines[i].strip())
            i += 1
        out.append(("p", " ".join(buf)))
    return out


def split_row(row):
    cells = re.split(r"(?<!\\)\|", row.strip())
    return [c.strip() for c in cells[1:-1]]


def comment_lines(text):
    return "\n".join("% " + ln.rstrip() if ln.strip() else "%" for ln in text.split("\n"))


def tabular(rows, spec, inline, small=r"\footnotesize"):
    head = split_row(rows[0])
    body = [split_row(r) for r in rows[2:]]
    out = [r"{" + small, r"\begin{tabular}{" + spec + "}", r"\hline"]
    out.append(" & ".join(r"\textbf{" + inline(c) + "}" if c else "" for c in head) + r" \\")
    out.append(r"\hline")
    for r in body:
        out.append(" & ".join(inline(c) for c in r) + r" \\")
    out += [r"\hline", r"\end{tabular}}"]
    return "\n".join(out)


def auto_spec(rows, width=r"\linewidth"):
    """Supplement tables: p-columns with widths proportional to the longest cell (bounded)."""
    cells = [split_row(r) for r in rows if not re.match(r"^\|[\s:|-]+\|$", r)]
    n = len(cells[0])
    lens = [max(6, min(60, max((len(r[k]) for r in cells if k < len(r)), default=6))) for k in range(n)]
    total = sum(lens)
    pad = 2 * n
    return "".join(r">{\raggedright\arraybackslash}p{" + f"{max(l / total, 0.06):.3f}" + r"\dimexpr" + width
                   + rf"-{pad}\tabcolsep\relax}}" for l in lens)


