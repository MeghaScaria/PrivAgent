SECTION_TITLES = {
    "I. INTRODUCTION": "Introduction", "II. RELATED WORK": "Related Work", "III. THREAT MODEL": "Threat Model",
    "IV. PRIVAGENT DESIGN": "PrivAgent Design", "V. STUDY DESIGN": "Study Design", "VI. RESULTS": "Results",
    "VII. DISCUSSION": "Discussion", "VIII. LIMITATIONS AND THREATS TO VALIDITY": "Limitations and Threats to Validity",
    "IX. CONCLUSION": "Conclusion",
}
UNNUMBERED = {"DATA AND CODE AVAILABILITY": "Data and Code Availability", "ACKNOWLEDGMENT": "Acknowledgment"}

P = r">{\raggedright\arraybackslash}p"
TABLE_SPECS = {  # table number -> (wide?, column spec)
    "I": (True, f"{P}{{2.2cm}}{P}{{1.5cm}}{P}{{2.5cm}}{P}{{3.0cm}}{P}{{2.7cm}}{P}{{3.6cm}}"),
    "II": (True, f"{P}{{2.6cm}}{P}{{5.6cm}}{P}{{8.2cm}}"),
    "III": (True, f"{P}{{2.0cm}}{P}{{6.6cm}}{P}{{7.8cm}}"),
    "IV": (True, f"{P}{{0.6cm}}{P}{{6.4cm}}{P}{{4.0cm}}{P}{{5.4cm}}"),
    "V": (False, f"{P}{{2.4cm}}{P}{{1.6cm}}rrrr"),
    "VI": (False, f"{P}{{3.4cm}}rr"),
    "VII": (True, f"{P}{{2.6cm}}" + f"{P}{{2.5cm}}" * 5),
    "VIII": (False, f"{P}{{1.9cm}}lrr"),
    "IX": (False, f"{P}{{2.4cm}}cccc"),
}
WIDE_FIGS = {"1"}


def convert_manuscript(md):
    md = re.sub(r"\A<!--\nSOURCE of .*?-->\n\n", "", md, flags=re.S)
    inline = Inline()
    title = re.search(r"^# (.+)$", md, re.M).group(1).strip()
    abstract = md[md.index("**Abstract**") + len("**Abstract**"):md.index("<!-- TEMPLATE: \\begin{IEEEkeywords}")]
    abstract = re.sub(r"<!-- DRAFT: author to review -->", "", abstract).strip()
    keywords = re.search(r"\*\*Index Terms:\*\*\s*(.+)$", md, re.M).group(1).strip().rstrip(".")
    body_md = md[md.index("## I. INTRODUCTION"):md.index("## REFERENCES")]
    bios_md = md[md.index("{{REFERENCES}}") + len("{{REFERENCES}}"):]

    bl = blocks(body_md)
    out, i = [], 0
    pending_caption = None
    while i < len(bl):
        b = bl[i]
        kind = b[0]
        if kind == "h":
            lvl, text = b[1], b[2]
            if lvl == 2 and text in SECTION_TITLES:
                label = text.split(".")[0]
                out.append(rf"\section{{{SECTION_TITLES[text]}}}\label{{sec:{label}}}")
            elif lvl == 2 and text in UNNUMBERED:
                out.append(rf"\section*{{{UNNUMBERED[text]}}}")
            elif lvl == 3:
                t = re.sub(r"^[A-Z]\.\s+", "", text)
                out.append(rf"\subsection{{{inline(t)}}}")
            else:
                raise SystemExit(f"unexpected heading: {text}")
        elif kind == "comment":
            out.append(comment_lines(b[1]))
        elif kind == "p" and re.match(r"^\*\*TABLE [IVX]+\.", b[1]):
            m = re.match(r"^\*\*TABLE ([IVX]+)\.\s*(.*?)\*\*\s*(.*)$", b[1])
            pending_caption = (m.group(1), m.group(2).strip(), m.group(3).strip())
        elif kind == "table":
            num, cap, note = pending_caption
            pending_caption = None
            wide, spec = TABLE_SPECS[num]
            env = "table*" if wide else "table"
            cap_tex = inline(cap.rstrip("."))
            note_tex = inline(note) if note else ""
            # a following ledger comment, then an optional italic note paragraph, belong to this table
            trailing = []
            j = i + 1
            while j < len(bl) and bl[j][0] == "comment":
                trailing.append(comment_lines(bl[j][1]))
                j += 1
            if j < len(bl) and bl[j][0] == "p" and re.match(r"^\*[^*].*\*$", bl[j][1]):
                note_tex = (note_tex + " " if note_tex else "") + inline(bl[j][1][1:-1])
                j += 1
            width = r"\textwidth" if wide else r"\columnwidth"
            t = [rf"\begin{{{env}}}[!t]", r"\centering", rf"\caption{{{cap_tex}}}\label{{tab:{num}}}",
                 r"\setlength{\tabcolsep}{4pt}", rf"\begin{{adjustbox}}{{max width={width}}}",
                 tabular(b[1], spec, inline), r"\end{adjustbox}"]
            if note_tex:
                t.append(r"\par\smallskip{\footnotesize\raggedright " + note_tex + r"\par}")
            t += trailing
            t.append(rf"\end{{{env}}}")
            out.append("\n".join(t))
            i = j
            continue
        elif kind == "fig":
            alt, path, trailing = b[1], b[2], b[3]
            m = re.match(r"^Fig\.\s*(\d+)\.\s*(.*)$", alt)
            num, cap = m.group(1), m.group(2)
            fname = os.path.basename(path)
            if fname.startswith("v2_f0_"):
                fname = fname.replace(".png", ".pdf")
            env = "figure*" if num in WIDE_FIGS else "figure"
            width = r"\textwidth" if num in WIDE_FIGS else r"\columnwidth"
            t = []
            if trailing:
                t.append(inline(trailing).strip())
            t += [rf"\begin{{{env}}}[!t]", r"\centering", rf"\includegraphics[width={width}]{{figures/{fname}}}",
                  rf"\caption{{{inline(cap)}}}\label{{fig:{num}}}", rf"\end{{{env}}}"]
            out.append("\n".join(t))
        elif kind in ("ul", "ol"):
            env = "itemize" if kind == "ul" else "enumerate"
            out.append(rf"\begin{{{env}}}" + "\n" + "\n".join(r"\item " + inline(it) for it in b[1])
                       + "\n" + rf"\end{{{env}}}")
        elif kind == "p":
            out.append(inline(b[1]))
        elif kind == "display":
            out.append(r"\[" + b[1] + r"\]")
        elif kind == "quote":
            out.append(r"\begin{quote}" + inline(b[1]) + r"\end{quote}")
        i += 1

    body = "\n\n".join(out)
    # biography placeholder
    bio = re.sub(r"<!--.*?-->", "", bios_md, flags=re.S).strip()
    bio_text = inline(re.sub(r"^\*\*\[AUTHOR NAME\]\*\*\s*", "", bio))
    return title, abstract, keywords, body, bio_text


