# ------------------------------------------------------------------------------------------ main
def figure_sources(md_texts):
    paths = set()
    for md in md_texts:
        for m in re.finditer(r"!\[.*?\]\((.*?)\)", md):
            paths.add(m.group(1))
    return paths


def main():
    os.makedirs(FIG_OUT, exist_ok=True)
    src = open(os.path.join(HERE, "manuscript_src.md"), encoding="utf-8").read()
    sup = open(os.path.join(V2, "SUPPLEMENTARY.md"), encoding="utf-8").read()

    # figures: resolve each relative path (relative to research_paper/v2/) and copy
    for rel in sorted(figure_sources([src, sup])):
        p = os.path.normpath(os.path.join(V2, rel))
        if not os.path.exists(p):
            raise SystemExit(f"missing figure: {rel}")
        shutil.copy2(p, os.path.join(FIG_OUT, os.path.basename(p)))
        if os.path.basename(p).startswith("v2_f0_"):
            pdf = p[:-4] + ".pdf"
            shutil.copy2(pdf, os.path.join(FIG_OUT, os.path.basename(pdf)))

    # template class, style and font files
    for f in sorted(os.listdir(TEMPLATE)):
        if f not in TEMPLATE_FILES_SKIP:
            shutil.copy2(os.path.join(TEMPLATE, f), os.path.join(OUT, f))

    with open(os.path.join(OUT, "PrivAgent_v2.tex"), "w", encoding="utf-8", newline="\n") as fh:
        fh.write(manuscript_tex(src))
    with open(os.path.join(OUT, "PrivAgent_v2_Supplementary.tex"), "w", encoding="utf-8", newline="\n") as fh:
        fh.write(supplement_tex(sup))

